  mano_obra_pct DECIMAL(5,2) NOT NULL DEFAULT 30.00,
  margen_beneficio_pct DECIMAL(5,2) NOT NULL DEFAULT 50.00,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
